# Запрос названия заказа и имени заказчика
название_заказа = input("Название заказа: ")
имя_заказчика = input("Имя заказчика: ")

# Первая позиция
название_позиц1 = input("Название первой позиции: ")
количество_позиц1 = int(input("Количество первой позиции: "))
цена_единицы_позиц1 = float(input("Цена единицы первой позиции (руб.): "))
стоимость_позиц1 = количество_позиц1 * цена_единицы_позиц1

# Вторая позиция
название_позиц2 = input("Название второй позиции: ")
количество_позиц2 = int(input("Количество второй позиции: "))
цена_единицы_позиц2 = float(input("Цена единицы второй позиции (руб.): "))
стоимость_позиц2 = количество_позиц2 * цена_единицы_позиц2

# Запрос стоимости доставки и внесённой суммы
стоимость_доставки = float(input("Стоимость доставки (руб.): "))
внесённая_сумма = float(input("Внесённая сумма (руб.): "))

# Расчёты
общая_стоимость_товаров = стоимость_позиц1 + стоимость_позиц2
общая_сумма_с_доставкой = общая_стоимость_товаров + стоимость_доставки
общее_количество_единиц = количество_позиц1 + количество_позиц2
сдача = внесённая_сумма - общая_сумма_с_доставкой

# Вывод результатов
print("\n--- Заказ ---")
print(f"Название: {название_заказа}")
print(f"Заказчик: {имя_заказчика}")
print("Позиции:")
print("Название | Количество | Цена | Стоимость")
print(f"{название_позиц1} | {количество_позиц1} | {цена_единицы_позиц1:.2f} | {стоимость_позиц1:.2f}")
print(f"{название_позиц2} | {количество_позиц2} | {цена_единицы_позиц2:.2f} | {стоимость_позиц2:.2f}")
print("Итоги:")
print(f"Стоимость товаров без доставки: {общая_стоимость_товаров:.2f} руб.")
print(f"Общая сумма с доставкой: {общая_сумма_с_доставкой:.2f} руб.")
print(f"Общее количество единиц: {общее_количество_единиц}")
print(f"Сдача: {сдача:.2f} руб.")
